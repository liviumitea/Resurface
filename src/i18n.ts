const dictionaries: Record<Language, Record<MessageKey, Message>> = { en, ro };
let current: Language = "en";

export function currentLanguage(): Language {
  return current;
}

export function setLanguage(language: Language): void {
  current = language;
}

/** Device language when it is Romanian, otherwise English. Never throws. */
export function deviceLanguage(): Language {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale ?? "";
    return locale.toLowerCase().startsWith("ro") ? "ro" : "en";
  } catch {
    return "en";
  }
}

export function resolveLanguage(preference: LanguagePreference): Language {
  return preference === "system" ? deviceLanguage() : preference;
}

/**
 * Plural category. English: one / other. Romanian (CLDR): one for 1; few for 0 and numbers whose
 * last two digits are 1–19 (other than 1 itself); other for the rest, which take "de" ("20 de idei").
 */
export function pluralCategory(count: number, language: Language = current): "one" | "few" | "other" {
  const n = Math.abs(Math.trunc(count));
  if (n === 1) return "one";
  if (language === "en") return "other";
  const lastTwo = n % 100;
  return n === 0 || (lastTwo >= 1 && lastTwo <= 19) ? "few" : "other";
}

function fill(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

function pick(message: Message, count: number | undefined, language: Language): string {
  if (typeof message === "string") return message;
  const category = pluralCategory(count ?? 0, language);
  return (category === "few" ? message.few ?? message.other : category === "one" ? message.one : message.other);
}

/** Translates a message; plural messages use `params.count`. Falls back to English. */
export function t(key: MessageKey, params: Record<string, string | number> = {}, language: Language = current): string {
  const message = dictionaries[language][key] ?? en[key];
  const count = typeof params.count === "number" ? params.count : undefined;
  return fill(pick(message, count, language), params);
}

/** BCP 47 locale used for dates; dates are always shown with a 24-hour clock in Romanian. */
export function dateLocale(language: Language = current): string {
  return language === "ro" ? "ro-RO" : "en-GB";
}

export function formatDate(value: string | Date, language: Language = current): string {
  return new Date(value).toLocaleDateString(dateLocale(language), { day: "numeric", month: "short", year: "numeric" });
}

export function formatDateTime(value: string | Date, language: Language = current): string {
  return new Date(value).toLocaleString(dateLocale(language), { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit", hour12: false });
}

/** Weekday name for 0 = Sunday … 6 = Saturday (4 January 2026 was a Sunday). */
export function weekdayName(day: number, style: "short" | "long" = "short", language: Language = current): string {
  return new Date(2026, 0, 4 + day).toLocaleDateString(dateLocale(language), { weekday: style });
}

export function formatLongDay(value: string | Date, language: Language = current): string {
  return new Date(value).toLocaleDateString(dateLocale(language), { weekday: "long", month: "long", day: "numeric" });
}

/** Every language's generic notification text, so stale-notification checks work after a switch. */
export function genericNotificationBodies(): Set<string> {
  return new Set((Object.keys(dictionaries) as Language[]).map((language) => t("notification.genericBody", {}, language)));
}

